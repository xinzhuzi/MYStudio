def strip_meta(t: str) -> str:
    """仅去「（硬,…)」类元语言括注与 markdown 符号,正文一字不动(甲案规格§剔除项)。"""
    t = re.sub(r"（硬[^）]*）", "", t)
    t = t.replace("（自动携带）", "")
    t = t.replace("**", "").replace("__", "")
    return t.strip()


