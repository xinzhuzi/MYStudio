def extract_lock_sections(md: str) -> dict:
    secs, cur = {}, None
    for ln in md.splitlines():
        m = re.match(r"^###\s+(\d)\.\s+", ln)
        if m:
            cur = m.group(1)
            secs[cur] = []
            continue
        if cur is None:
            continue
        if ln.startswith("###") or ln.startswith("## ") or ln.startswith("---"):
            cur = None
            continue
        if ln.strip():
            secs[cur].append(ln.strip())
    return {k: "\n".join(v) for k, v in secs.items()}


