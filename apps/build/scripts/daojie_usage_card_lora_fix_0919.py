def main() -> int:
    raw = WF.read_text(encoding="utf-8")
    data = json.loads(raw)
    note = next((n for n in data["nodes"] if n.get("id") == 66), None)
    if note is None or note.get("type") != "MarkdownNote":
        print("FAIL: 找不到节点 [66] MarkdownNote")
        return 1
    old = note["widgets_values"][0]
    if "用法速查" not in old:
        print("FAIL: [66] 不是用法速查卡,内容头部异常")
        return 1
    if old == NEW_NOTE:
        print("OK: 已是目标文本,无需改动(幂等)")
        return 0
    note["widgets_values"][0] = NEW_NOTE
    out = json.dumps(data, ensure_ascii=False, indent=2)
    WF.write_text(out, encoding="utf-8")

    # 自验:重载比对,且除 [66] 外节点集合与 mode 不变
    check = json.loads(WF.read_text(encoding="utf-8"))
    got = next(n for n in check["nodes"] if n.get("id") == 66)["widgets_values"][0]
    assert got == NEW_NOTE, "回写后 [66] 文本不一致"
    assert len(check["nodes"]) == len(data["nodes"])
    before = {n["id"]: (n["type"], n.get("mode", 0)) for n in json.loads(raw)["nodes"]}
    after = {n["id"]: (n["type"], n.get("mode", 0)) for n in check["nodes"]}
    assert before == after, "除 [66] 文本外有节点被动到"
    print(f"OK: [66] 用法速查已重写(旧 {len(old)} 字 → 新 {len(got)} 字),其余节点零改动")
    return 0


if __name__ == "__main__":
    sys.exit(main())
