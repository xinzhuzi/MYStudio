def build_readme(entries: list[dict]) -> None:
    media_count: dict[str, int] = {}
    for e in entries:
        media_count[e["media"]] = media_count.get(e["media"], 0) + 1
    stats = "、".join(f"{k} {v} 条" for k, v in sorted(media_count.items()))
    readme = f"""# 人像美学提示词库(portrait_aesthetics)

KOOK 社区人像美学图集提示词收录(两期 40 条,2026-09-17 收录),为 K2 人物出像线供词。

- 主库:[人像美学提示词库.md](./人像美学提示词库.md)(分类索引+全文+六层词汇银行+借用指南)
- 原文存档:`raw/第一期|第二期/NN.txt`
- 构成:{stats}
- 铁律:借词不借形态——Qwen 编码器吃语句体,把词汇银行的词织进完整句子再入提示词(09-16 X7 实证)
- 关联:[K2 工笔负面清单](../../../docs/comfyui-kb/K2工笔负面清单.md) · [参数速查](../../../docs/comfyui-kb/参数速查.md)
"""
    (DST / "README.md").write_text(readme, encoding="utf-8")


def main() -> None:
    assert SRC.is_dir(), f"源目录不存在: {SRC}"
    entries = load_entries()
    assert len(entries) == 40, f"应 40 条,实 {len(entries)}"
    DST.mkdir(parents=True, exist_ok=True)
    write_raw(entries)
    build_db(entries)
    build_readme(entries)
    raw_n = len(list((DST / "raw").rglob("*.txt")))
    print(f"建库完成:40 条目 | raw 存档 {raw_n} | 落位 {DST}")


if __name__ == "__main__":
    main()
