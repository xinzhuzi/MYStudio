def classify(text: str) -> str:
    for name, pat in MEDIA_RULES:
        if re.search(pat, text, re.I):
            return name
    return "混合媒介系"


def classify_gender(text: str) -> str:
    if re.search(r"两人|男女", text):
        return "双人"
    if re.search(r"帅哥|美男|俊美少年|年轻男性|男子", text):
        return "男像"
    if re.search(r"少女|女孩|女子|美女|女人|她", text):
        return "女像"
    return "未标注"


def load_entries() -> list[dict]:
    entries = []
    for qi, qdir in enumerate(["第一期", "第二期"], 1):
        for p in sorted((SRC / qdir).glob("*.txt"), key=lambda x: int(x.stem)):
            text = re.sub(r"\s+", " ", p.read_text(encoding="utf-8", errors="replace")).strip()
            n = int(p.stem)
            entries.append({
                "qi": qi, "n": n, "text": text, "len": len(text),
                "media": classify(text), "gender": classify_gender(text),
                "theme": THEMES.get((qi, n), ""),
            })
    return entries


def write_raw(entries: list[dict]) -> None:
    for e in entries:
        raw_dir = DST / "raw" / f"第{('一', '二')[e['qi'] - 1]}期"
        raw_dir.mkdir(parents=True, exist_ok=True)
        src = SRC / f"第{('一', '二')[e['qi'] - 1]}期" / f"{e['n']}.txt"
        shutil.copy2(src, raw_dir / f"{e['n']:02d}.txt")


