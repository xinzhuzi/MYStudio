def main() -> None:
    data = json.loads(BASES.read_text(encoding="utf-8"))
    old = data["expand_instruction"]["system_prompt_zh"]
    palette = old[old.index("### 项目色卡全库"):old.index("## 透明模式")]
    new = NEW_HEAD + palette + NEW_TAIL
    for step in range(1, 9):
        assert f"### 第{'一二三四五六七八'[step-1]}步" in new, step
    # 七处去冲突语义全在场
    for key in ("裁决序", "永不豁免", "只管新增色", "透明底立绘素材",
                "删环境、留部件", "最简整数比", "润炼模式", "扩写模式",
                "不出现「背景」", "此席让给主体色"):
        assert key in new, key
    data["expand_instruction"]["system_prompt_zh"] = new
    BASES.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                     encoding="utf-8")
    wf = json.loads(WF.read_text(encoding="utf-8"))
    hit = 0
    for sg in wf.get("definitions", {}).get("subgraphs", []):
        for n in sg.get("nodes", []):
            if n.get("type") == "MyQi21系统提示词":
                n["widgets_values"] = [new]
                hit += 1
    WF.write_text(json.dumps(wf, ensure_ascii=False, indent=2) + "\n",
                  encoding="utf-8")
    print(f"真源: {len(old)} -> {len(new)} 字符;展示框 {hit} 处")


if __name__ == "__main__":
    sys.exit(main())
