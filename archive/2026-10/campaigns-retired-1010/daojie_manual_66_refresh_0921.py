    n66 = next(n for n in wf["nodes"] if n.get("id") == 66)
    for old, new in REPL:
        for holder in (n66["widgets_values"], n66["widgets_values_named"]):
            key = 0 if holder is n66["widgets_values"] else "text"
            cur = holder[key]
            if new in cur:
                continue  # 幂等:已是新文
            cnt = cur.count(old)
            assert cnt >= 1, f"未找到待修片段: {old[:30]}..."
            holder[key] = cur.replace(old, new)
    WF.write_text(json.dumps(wf, ensure_ascii=False, indent=2))
