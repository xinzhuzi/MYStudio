#!/usr/bin/env python3
"""道劫主图布局重排(09-21,用户裁定:每链横向一行禁纵塔)。

旧布局病灶:模型链被拆三段——[21]DiT(40)→[90]栈(6480)→[12]采样(3997),
model 线横穿全画布;[86]/[91] 远端纵挂。
新布局:
  ① 模型加载+LoRA栈([21][15][10] 顶行,[90] 接续同区,模型链完整从左到右)
  ③ 提示词链一行([50]→[80]→[51]/[65]→[63]→[62])
  ④ 画布与采样一行([53]/[20]/[61]→[12]→[11]→[4])
  右侧竖排 [66] 速查+[91] 图解;[86] 生效清单挂 [90] 正下方。
"""
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
WF = REPO / "apps/backend/engines/comfyui/workflows/1_图片/K2图像/1_文生图/K2-文生图-道劫.json"

# id -> (x, y)  ;尺寸保持节点现值
POS = {
    21: (40, 80),      # DiT加载
    15: (440, 80),     # TE加载
    10: (840, 80),     # VAE加载
    90: (1240, 80),    # LoRA栈·九型驱动(模型链第4件,高980独占纵空间)
    50: (1740, 380),   # 主体句
    80: (2460, 380),   # 道劫底座
    64: (1740, 660),   # 负向基线
    51: (3200, 380),   # 正向编码
    65: (3200, 660),   # 负向编码
    63: (3690, 380),   # 12带重平衡
    62: (4320, 380),   # 最终正向预览
    53: (4860, 380),   # 空画布
    20: (4860, 660),   # 种子
    61: (4860, 850),   # 分辨率(退位,旁路挂[53]下方)
    12: (5260, 380),   # KSampler
    11: (5630, 380),   # 解码出图
    4:  (5930, 380),   # 保存图片
    66: (6350, 380),   # 用法速查
    86: (1240, 1100),  # 生效清单([90]正下方)
    91: (6350, 1450),  # LoRA逻辑图解(速查下方)
}

GROUPS = [
    {"id": 1, "title": "① 模型加载+LoRA栈([21]→[90] 模型链;[90]双击=九型配方矩阵)",
     "bounding": [20, 40, 1660, 1300], "color": "#3f789e", "flags": {}},
    {"id": 2, "title": "③ 提示词链(主体句→底座→编码→12带;[64]→[65] 负向支线)",
     "bounding": [1700, 340, 3060, 580], "color": "#4d9e6a", "flags": {}},
    {"id": 3, "title": "④ 画布与采样出图([61]已退位旁路;[20]种子→[12]→[11]→[4])",
     "bounding": [4820, 340, 1520, 700], "color": "#c27a3d", "flags": {}},
    {"id": 4, "title": "说明书([66]用法速查+[91]LoRA逻辑图解·纯展示)",
     "bounding": [6310, 340, 780, 1470], "color": "#8a5fb0", "flags": {}},
]


def main():
    doc = json.loads(WF.read_text(encoding="utf-8"))
    moved = 0
    for n in doc["nodes"]:
        nid = n.get("id")
        if nid in POS:
            n["pos"] = list(POS[nid])
            moved += 1
    doc["groups"] = GROUPS
    WF.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"主图重排:{moved} 节点归位,{len(GROUPS)} 组框")


if __name__ == "__main__":
    main()
